# Pure shell, zero Nix dependency: configuration comes through
# STATEBACKUP_* environment variables (injected by the facade at build time).
# Standalone test: bash t0.sh
# Usage:
#   nas-backup dump [job...]         backup jobs (default: all) + GFS rotation
#   nas-backup rotate [job...]       promotion + prune only
#   nas-backup list                 show the GFS grid (read-only)
#   nas-backup restore <job> [--file <path>]
# Exit codes: 0 ok, 1 at least one job failed, 2 usage.

set -uo pipefail
shopt -s nullglob

ROOT="${STATEBACKUP_ROOT:?STATEBACKUP_ROOT must be set}"
NOW="${STATEBACKUP_NOW:-$(date +%Y%m%d-%H%M%S)}"
GITREV="${STATEBACKUP_GIT_REV:-unknown}"
ALL_JOBS="${STATEBACKUP_ALL_JOBS:-}"

if [ -n "${STATEBACKUP_JOBS_FILE:-}" ]; then
  # Registry generated by the Nix facade: job_<j>_dump/_restore/_units.
  # shellcheck source=/dev/null
  source "$STATEBACKUP_JOBS_FILE"
fi

# ─── GFS grid ────────────────────────────────────────────────────────
# daily/   one dump per run, kept for the current ISO week (window)
# weekly/  one per week, kept for the current month        (window)
# monthly/ one per month, kept for the current year        (window)
# yearly/  one per year, kept forever                      (bucket)
# Timestamps sort lexicographically == chronologically.

day() { local d="${1:0:4}-${1:4:2}-${1:6:2}"; shift; date -d "$d" "$@"; }

# Window rule: is this stamp inside the tier's CURRENT period?
in_window() { # $1 tier, $2 stamp, $3 now-stamp
  case "$1" in
    daily)   [ "$(day "$2" +%G-W%V)" = "$(day "$3" +%G-W%V)" ] ;;
    weekly)  [ "$(day "$2" +%Y-%m)"  = "$(day "$3" +%Y-%m)"  ] ;;
    monthly) [ "$(day "$2" +%Y)"     = "$(day "$3" +%Y)"     ] ;;
    yearly)  true ;;
  esac
}

# Promotion key: the sub-period a stamp represents in the tier ABOVE it.
promote_key() { # $1 upper tier, $2 stamp
  case "$1" in
    weekly)  day "$2" +%G-W%V ;;
    monthly) day "$2" +%Y-%m  ;;
    yearly)  day "$2" +%Y     ;;
  esac
}

# ─── Prune: window tiers delete out-of-period files; yearly keeps one
# per year (newest wins, manifest deleted with its dump) ─────────────
prune_tier() { # $1 tier, $2 dir, $3 now-stamp
  local tier="$1" dir="$2" now="$3"
  local -A kept=()
  local f stamp key
  for f in "$dir"/*.dump; do
    stamp=$(basename "$f" .dump)
    if [ "$tier" = yearly ]; then
      key=$(day "$stamp" +%Y)
      if [ -n "${kept[$key]:-}" ]; then
        if [[ "$stamp" < "${kept[$key]}" ]]; then
          rm -f "$f" "$f.manifest"
        else
          rm -f "$dir/${kept[$key]}.dump" "$dir/${kept[$key]}.dump.manifest"
          kept[$key]="$stamp"
        fi
      else
        kept[$key]="$stamp"
      fi
    else
      in_window "$tier" "$stamp" "$now" || rm -f "$f" "$f.manifest"
    fi
  done
}

# ─── Rotate: promote the newest daily to empty buckets, then prune ──
# Promotion happens at period START (first dump of a week/month/year);
# promotion checks make it idempotent within a period.
rotate() { # $1 job
  local job="$1" jdir="$ROOT/$1"
  local t f g newest="" stamp key have
  mkdir -p "$jdir"/{daily,weekly,monthly,yearly}

  for f in "$jdir/daily"/*.dump; do newest="$f"; done  # sorted: last = newest
  if [ -n "$newest" ]; then
    stamp=$(basename "$newest" .dump)
    for t in weekly monthly yearly; do
      key=$(promote_key "$t" "$stamp")
      have=""
      for g in "$jdir/$t"/*.dump; do
        if [ "$(promote_key "$t" "$(basename "$g" .dump)")" = "$key" ]; then have=1; break; fi
      done
      if [ -z "$have" ]; then
        # cp -p keeps the original mtime; a hardlink would not be valid
        # across mergerfs underlying disks.
        cp -p "$newest" "$jdir/$t/"
        [ -e "$newest.manifest" ] && cp -p "$newest.manifest" "$jdir/$t/"
      fi
    done
  fi
  for t in daily weekly monthly yearly; do prune_tier "$t" "$jdir/$t" "$NOW"; done
}

# ─── Dump: atomic write + provenance manifest + rotate ───────────────
dump_job() { # $1 job
  local job="$1" jdir="$ROOT/$1"
  local tmp="$jdir/daily/.$NOW.tmp"
  local final="$jdir/daily/$NOW.dump"
  mkdir -p "$jdir/daily"

  # The job writes into a dotfile: a failed dump NEVER becomes a final
  # file, so SnapRAID can never sync a partial dump.
  "job_${job}_dump" "$tmp"

  # A job failing SILENTLY (exit 0, no output) must not produce an
  # empty final dump.
  [ -s "$tmp" ] || { echo "backup: $job produced no output" >&2; exit 1; }

  cat > "$tmp.manifest" <<EOF
date=$NOW
host=$(hostname -s)
git_rev=$GITREV
job=$job
EOF

  # mv within the same directory is an atomic rename; chown enforces the
  # mergerfs pool single-owner invariant.
  mv "$tmp" "$final"
  mv "$tmp.manifest" "$final.manifest"
  chown 1000:100 "$final" "$final.manifest"
  rotate "$job"
  echo "backup: $job done ($final)"
}

# ─── Restore: interactive, with pre-restore safety dump ───────────────
restore_job() { # $1 job, rest: [--file path]
  local job="$1"; shift
  local jdir="$ROOT/$job" file=""
  while [ $# -gt 0 ]; do
    case "$1" in
      --file) file="$2"; shift 2 ;;
      *) shift ;;
    esac
  done
  if [ -z "$file" ]; then
    local f
    for f in "$jdir/daily"/*.dump; do file="$f"; done  # newest daily
  fi
  if [ -z "$file" ] || [ ! -e "$file" ]; then
    echo "restore: no dump found for $job" >&2; exit 1
  fi

  echo "== restore $job from: $file"
  [ -e "$file.manifest" ] && cat "$file.manifest"
  local answer
  read -r -p "This OVERWRITES the live state of '$job'. Type the job name to confirm: " answer
  [ "$answer" = "$job" ] || { echo "aborted."; exit 1; }

  local safety="$jdir/daily/$(date +%Y%m%d-%H%M%S).dump"
  "job_${job}_dump" "$jdir/daily/.safety.tmp"
  { mv "$jdir/daily/.safety.tmp" "$safety"; chown 1000:100 "$safety"; }
  echo "== pre-restore safety dump: $safety"

  local units
  units=$("job_${job}_units")
  [ -n "$units" ] && systemctl stop $units
  "job_${job}_restore" "$file"
  [ -n "$units" ] && systemctl start $units
  sleep 5
  local u
  for u in $units; do
    systemctl is-active --quiet "$u" || { echo "restore: unit $u not active after restore!" >&2; exit 1; }
  done
  echo "== restore done. Rollback if needed: nas-backup restore $job --file $safety"
}

# ─── List: the GFS grid, read-only ───────────────────────────────────
list() {
  local job t f
  for job in $ALL_JOBS; do
    echo "== $job"
    for t in daily weekly monthly yearly; do
      for f in "$ROOT/$job/$t"/*.dump; do
        echo "  $t/$(basename "$f")"
      done
    done
  done
}

# ─── Dispatch ───────────────────────────────────────────────────────
case "${1:-}" in
  dump)
    shift
    jobs=("$@"); [ ${#jobs[@]} -eq 0 ] && jobs=($ALL_JOBS)
    failed=0
    # Each job in its own set -e subshell: one failure does not block the
    # others, and the final exit puts the systemd unit in "failed" state
    # → OnFailure → ntfy.
    for j in "${jobs[@]}"; do
      ( set -e; dump_job "$j" )
	  [ $? -ne 0 ] && { echo "backup FAILED: $j" >&2; failed=1; }
    done
    exit $failed
    ;;
  rotate)
    shift
    jobs=("$@"); [ ${#jobs[@]} -eq 0 ] && jobs=($ALL_JOBS)
    for j in "${jobs[@]}"; do rotate "$j"; done
    ;;
  restore)
    shift
    [ $# -ge 1 ] || { echo "restore: job required" >&2; exit 2; }
    restore_job "$@"
    ;;
  list)
    list
    ;;
  *)
	usage() {
  cat <<'EOF'
Usage:
  nas-backup dump [job...]         backup jobs (default: all) + GFS rotation
  nas-backup rotate [job...]       promotion + prune only
  nas-backup list                 show the GFS grid (read-only)
  nas-backup restore <job> [--file <path>]
EOF
  exit 2
}
    ;;
esac
